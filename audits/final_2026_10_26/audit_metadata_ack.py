"""Unit check of the exact new upstream branch; no malformed network traffic.

Valid metadata is generated by OutgoingFile. A controlled receiver rejection
tests the callback's ACK decision; this is not an end-to-end malformed packet test.
"""
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

OUT = Path(__file__).resolve().parent
ROOT = OUT.parents[1]
sys.path.insert(0, str(ROOT))
from file_client import FileTransferHandler
from file_transfer import OutgoingFile, FileTransferError, encode_secure_json, decode_secure_json
from protocol import Packet, MSG_DATA


class MetadataACK(unittest.TestCase):
    def exercise(self, reject):
        with tempfile.TemporaryDirectory(prefix="audit-meta-") as directory:
            sent = []
            handler = FileTransferHandler(lambda packet, recipient: sent.append((packet, recipient)), lambda: 1, directory)
            meta = OutgoingFile.from_bytes("normal.txt", b"valid metadata control").metadata_message("bob")
            packet = Packet(MSG_DATA, payload=encode_secure_json(meta))
            if reject:
                with patch.object(handler.receiver, "accept_metadata", side_effect=FileTransferError("controlled receiver rejection")):
                    self.assertTrue(handler.handle_packet(packet, "alice"))
                self.assertEqual(sent, [], "Rejected metadata must not be ACKed as accepted")
                self.assertEqual(handler.get_progress(), [])
            else:
                self.assertTrue(handler.handle_packet(packet, "alice"))
                self.assertEqual(len(sent), 1)
                self.assertEqual(decode_secure_json(sent[0][0].payload)["chunk_index"], -1)
                self.assertEqual(handler.get_progress()[0]["status"], "receiving")

    def test_valid_metadata_gets_ack(self):
        self.exercise(False)

    def test_receiver_rejection_gets_no_ack(self):
        self.exercise(True)


if __name__ == "__main__":
    result = unittest.TextTestRunner(verbosity=2).run(unittest.defaultTestLoader.loadTestsFromTestCase(MetadataACK))
    data = {"baseline": subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip(),
        "total": result.testsRun, "pass": result.testsRun - len(result.failures) - len(result.errors),
        "fail": len(result.failures), "error": len(result.errors),
        "scope": "unit test with controlled receiver rejection; no malformed-packet/network claim"}
    (OUT / "metadata_ack_latest.json").write_text(json.dumps(data, indent=2), encoding="utf-8")
    raise SystemExit(0 if result.wasSuccessful() else 1)
